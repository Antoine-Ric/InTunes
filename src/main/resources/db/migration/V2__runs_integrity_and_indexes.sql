-- No legacy data is deleted. Conflicting rows abort this transactional migration.
CREATE TABLE matchup_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users,
    genre varchar(50) NOT NULL,
    status varchar(20) NOT NULL,
    started_at timestamp(6) with time zone NOT NULL,
    finished_at timestamp(6) with time zone,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT ck_runs_genre CHECK (genre IN ('hiphop','rnb','afrobeats','pop','country','gospel','rock')),
    CONSTRAINT ck_runs_status CHECK (status IN ('IN_PROGRESS','COMPLETED','ABANDONED')),
    CONSTRAINT ck_runs_finished CHECK (
        (status = 'IN_PROGRESS' AND finished_at IS NULL) OR
        (status IN ('COMPLETED','ABANDONED') AND finished_at IS NOT NULL AND finished_at >= started_at)),
    CONSTRAINT uq_runs_context UNIQUE (id, user_id, genre)
);

-- The old schema represents one attempt per user/genre. A profile proves completion;
-- other historical activity becomes an in-progress attempt, with ratings preserved.
INSERT INTO matchup_runs (user_id, genre, status, started_at, finished_at)
SELECT activity.user_id, activity.genre,
       CASE WHEN profile.id IS NULL THEN 'IN_PROGRESS' ELSE 'COMPLETED' END,
       min(activity.at),
       CASE WHEN profile.id IS NOT NULL THEN max(activity.at) END
FROM (
    SELECT user_id, genre, created_at AS at FROM matchups
    UNION ALL
    SELECT user_id, genre, created_at FROM taste_profiles
    UNION ALL
    SELECT rating.user_id, song.genre, usr.created_at
    FROM song_ratings rating JOIN songs song ON song.id = rating.song_id
    JOIN users usr ON usr.id = rating.user_id
) activity
LEFT JOIN taste_profiles profile ON profile.user_id = activity.user_id AND profile.genre = activity.genre
GROUP BY activity.user_id, activity.genre, profile.id;

