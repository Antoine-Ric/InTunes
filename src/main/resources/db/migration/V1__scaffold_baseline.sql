-- Snapshot of the pre-Flyway Hibernate scaffold. Existing databases baseline at 1.
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL CONSTRAINT uq_users_username UNIQUE,
    password_hash varchar(255) NOT NULL,
    display_name varchar(100),
    created_at timestamp(6) with time zone NOT NULL
);
CREATE TABLE songs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spotify_id varchar(64) CONSTRAINT uq_songs_spotify UNIQUE,
    title varchar(255) NOT NULL,
    artist varchar(255) NOT NULL,
    album_art_url varchar(512),
    preview_url varchar(512),
    genre varchar(50) NOT NULL,
    popularity integer,
    release_year integer
);
CREATE TABLE song_ratings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users,
    song_id bigint NOT NULL REFERENCES songs,
    rating double precision NOT NULL,
    matchups_played integer NOT NULL,
    CONSTRAINT uq_ratings_user_song UNIQUE (user_id, song_id)
);
CREATE TABLE matchups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users,
    songa_id bigint NOT NULL REFERENCES songs,
    songb_id bigint NOT NULL REFERENCES songs,
    winner_id bigint NOT NULL REFERENCES songs,
    genre varchar(50) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL
);
CREATE TABLE taste_profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users,
    genre varchar(50) NOT NULL,
    archetype_key varchar(100) NOT NULL,
    archetype_name varchar(100) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_profiles_user_genre UNIQUE (user_id, genre)
);
CREATE TABLE communities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archetype_key varchar(100) NOT NULL CONSTRAINT uq_communities_archetype UNIQUE,
    name varchar(100) NOT NULL,
    description varchar(500)
);
CREATE TABLE posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id bigint NOT NULL REFERENCES communities,
    author_id bigint NOT NULL REFERENCES users,
    body varchar(2000) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL
);
CREATE TABLE replies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL REFERENCES posts,
    author_id bigint NOT NULL REFERENCES users,
    body varchar(2000) NOT NULL,
    pinned boolean NOT NULL,
    created_at timestamp(6) with time zone NOT NULL
);
CREATE TABLE likes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users,
    post_id bigint REFERENCES posts,
    reply_id bigint REFERENCES replies,
    created_at timestamp(6) with time zone NOT NULL
);
